SELECT Дата_поставки, Наименование_товара
FROM   ЗАКАЗЫ
WHERE (Дата_поставки >= CONVERT(DATETIME, '2025-01-01 00:00:00', 102))
SELECT Наименование, Цена
FROM   ТОВАРЫ
WHERE (Цена >= 60 AND Цена <= 150)
SELECT Наименование_товара, Заказчик
FROM   ЗАКАЗЫ
WHERE (Наименование_товара IN (N'Зеркало'))
SELECT Заказчик, Наименование_товара, Дата_поставки
FROM   ЗАКАЗЫ
WHERE (Заказчик IN (N'Доманиус'))
ORDER BY Дата_поставки